// Generates the JSON Schema validators as plain code, compiled once at build time with Ajv's
// standalone mode. At runtime nothing compiles code, so the web app needs no 'unsafe-eval' in its
// CSP, and Ajv's compiler isn't bundled anywhere.
//
//   node scripts/build-validators.mjs [--check]   (--check fails if the files are out of date)

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { Ajv2020 } from "ajv/dist/2020.js";
import { Ajv, _ } from "ajv";
import addFormatsModule from "ajv-formats";
import standaloneModule from "ajv/dist/standalone/index.js";

const addFormats = addFormatsModule.default ?? addFormatsModule;
const standaloneCode = standaloneModule.default ?? standaloneModule;
const read = (p) => JSON.parse(readFileSync(p, "utf8"));
const session = read("schema/session.schema.json");
const framework = read("schema/framework.schema.json");
// Interview engine v2: the model's three calls and the summary write-up.
const v2 = Object.fromEntries(["opening", "phrase", "extract", "writeup"].map((n) => [n, read(`schema/v2/${n}.schema.json`)]));

// Formats are referenced from ajv-formats' plain format table, not compiled code.
// inlineRefs: false keeps each shared $def as one function instead of copying it into every use.
const options = { strict: true, allErrors: true, inlineRefs: false, code: { source: true, esm: true, formats: _`require("ajv-formats/dist/formats").fullFormats` } };

function generate(ajv, refs) {
  addFormats(ajv);
  return standaloneCode(ajv, refs);
}

const sessionCode = generate(new Ajv2020(options).addSchema(session, "session"), { validateSession: "session" });
const v2Ajv = new Ajv2020(options);
for (const [name, schema] of Object.entries(v2)) v2Ajv.addSchema(schema, name);
const v2Code = generate(v2Ajv, { validateOpening: "opening", validatePhrase: "phrase", validateExtract: "extract", validateWriteUp: "writeup" });
const id = framework.$id;
const frameworkCode = generate(new Ajv2020(options).addSchema(framework), {
  router: `${id}#/$defs/router`,
  module: `${id}#/$defs/module`,
  scoring: `${id}#/$defs/scoring`,
  sections: `${id}#/$defs/sections`,
});

// The fact names both data schemas allow; framework.ts checks them against scoring.yaml.
const facts = {
  writeup: v2.writeup.$defs.fact.properties.fact.enum,
  session: session.$defs.item.properties.facts.propertyNames.enum,
};
const coreAreas = session.properties.core.required;

const HEADER = "// GENERATED by scripts/build-validators.mjs from schema/*.json. Don't edit; run npm run build.";

// Ajv's standalone output still require()s a few small CommonJS runtime helpers. Node and
// bundlers disagree about those modules' default export, so each is swapped for the plain-ESM
// equivalent in src/lib/schema-runtime.ts. An unexpected helper fails the build.
const RUNTIME = {
  "ajv/dist/runtime/equal": "__rt.equal",
  "ajv/dist/runtime/ucs2length": "__rt.ucs2",
  "ajv-formats/dist/formats": "__rt.formats",
};
function emit(code) {
  const esm = code.replace(/require\("([^"]+)"\)/g, (_m, spec) => {
    if (!RUNTIME[spec]) throw new Error(`generated validator needs runtime helper ${spec}: add it to src/lib/schema-runtime.ts and RUNTIME`);
    return RUNTIME[spec];
  });
  return [HEADER, 'import * as __rt from "../schema-runtime.ts";', esm.replace(/^"use strict";/, "")].join("\n");
}

// Separate files, so each bundle carries only what it uses (the browser needs none of the
// framework validators), and because each standalone chunk names its helpers validate10,
// schema31 and so on, so they can't share one module scope.
const files = {
  "src/lib/generated/session-validator.js": `${emit(sessionCode)}\n`,
  "src/lib/generated/v2-validators.js": `${emit(v2Code)}\n`,
  "src/lib/generated/framework-validators.js": `${emit(frameworkCode)}\n`,
  "src/lib/generated/schema-facts.js": `${HEADER}\nexport const factNames = ${JSON.stringify(facts, null, 2)};\nexport const coreAreas = ${JSON.stringify(coreAreas)};\n`,
};
// Declarations, so TypeScript can import the generated JavaScript without allowJs.
const fn = (name) => `export declare const ${name}: ValidateFunction;`;
const types = `${HEADER}\nimport type { ValidateFunction } from "ajv";`;
Object.assign(files, {
  "src/lib/generated/session-validator.d.ts": `${types}\n${fn("validateSession")}\n`,
  "src/lib/generated/v2-validators.d.ts": `${types}\n${["validateOpening", "validatePhrase", "validateExtract", "validateWriteUp"].map(fn).join("\n")}\n`,
  "src/lib/generated/framework-validators.d.ts": `${types}\n${["router", "module", "scoring", "sections"].map(fn).join("\n")}\n`,
  "src/lib/generated/schema-facts.d.ts": `${HEADER}\nexport declare const factNames: { writeup: string[]; session: string[] };\nexport declare const coreAreas: string[];\n`,
});

const check = process.argv.includes("--check");
let stale = false;
for (const [file, out] of Object.entries(files)) {
  if (check) {
    if (!existsSync(file) || readFileSync(file, "utf8") !== out) {
      console.error(`${file} is out of date: run npm run build`);
      stale = true;
    }
  } else {
    mkdirSync("src/lib/generated", { recursive: true });
    writeFileSync(file, out);
    console.log(`wrote ${file} (${(out.length / 1024).toFixed(0)} kB)`);
  }
}
if (stale) process.exit(1);
