// Replays the async worked example with no model: the recorded answers in examples/async-example/recorded/ are
// put in .intake-kit/calls before each step, exactly as Claude would write them.
//
//   node scripts/replay-async-example.mjs [--write]      (--write updates examples/async-example/output/)
//
// Prints each step's result. With --write, saves the walkthrough (every step's output, as shown to
// the interviewer) and both spec packs: output/final/ (main path) and output/early/ (signed off
// straight after the notes). tests/async-example.test.ts checks the replay matches what's committed.

import { spawnSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { EXAMPLE, FIXED, PACK, STEPS } from "./async-example-steps.mjs";

/** Runs the whole example in scratch folders; returns each step's output and both spec packs. */
export function replay(root = ".") {
  const main = mkdtempSync(join(tmpdir(), "intake-replay-"));
  const early = `${main}-early`;
  const sources = resolve(root, EXAMPLE, "sources");
  const results = [];
  let packet = "";
  try {
    for (const step of STEPS) {
      const dir = step.branch === "early" ? early : main;
      if (step.branch === "early" && !existsSync(early)) cpSync(main, early, { recursive: true });
      const recorded = resolve(root, EXAMPLE, "recorded", step.id);
      if (existsSync(recorded)) cpSync(recorded, join(dir, ".intake-kit", "calls"), { recursive: true });
      const args = step.args.map((a) => a.replace("SOURCES", sources));
      const r = spawnSync(process.execPath, [resolve(root, "dist/intake.mjs"), ...args, "--dir", dir], { encoding: "utf8", env: { ...process.env, ...FIXED } });
      const body = JSON.parse(r.stdout);
      if (r.status !== 0) throw new Error(`${step.id}: exit ${r.status}: ${JSON.stringify(body).slice(0, 400)}`);
      results.push({ step, body });
      if (body.result === "triaged") packet = readFileSync(join(dir, ".intake-kit", "packet.md"), "utf8");
    }
    const pack = (dir) => Object.fromEntries(PACK.filter((f) => existsSync(join(dir, f))).map((f) => [f, readFileSync(join(dir, f), "utf8")]));
    return { results, packet, final: pack(main), early: pack(early) };
  } finally {
    rmSync(main, { recursive: true, force: true });
    rmSync(early, { recursive: true, force: true });
  }
}

/** The walkthrough: what the interviewer sees at each step, from the replay's real output. */
export function walkthrough(results) {
  const md = ["# Async worked example: walkthrough", "", "Generated by `node scripts/replay-async-example.mjs --write` from the recorded run: no model calls. Sources are synthetic (`sources/`).", ""];
  const show = (title, lines) => md.push(`## ${title}`, "", ...lines, "");
  const block = (text) => ["```text", text.trimEnd(), "```"];
  for (const { step, body } of results) {
    const where = step.branch === "early" ? " (early branch: signed off straight after the notes)" : "";
    const cmd = `\`intake.mjs ${step.args.map((a) => (a.includes(" ") ? `"${a}"` : a.replace("SOURCES/", "sources/"))).join(" ")}\`${where}`;
    if (body.result === "triaged") show(`${step.id}: triage`, [cmd, "", "Readiness:", "", ...body.readiness.map((l) => `- ${l}`), "", `The question packet is written to \`.intake-kit/packet.md\` (see \`packet.md\` here).`]);
    else if (body.result === "ingested" || body.result === "gaps") show(`${step.id}: ${step.args[0]}`, [cmd, "", "Readiness:", "", ...body.readiness.map((l) => `- ${l}`), "", ...(body.followup_text ? ["Follow-up packet (round 2):", "", ...block(body.followup_text)] : [body.next ?? ""])]);
    else if (body.result === "summary") show(`${step.id}: summary`, [cmd, "", ...block(body.summary), "", ...(body.confirm.length ? ["Don't-build reasons to confirm, one at a time:", "", ...body.confirm.map((c) => `- \`${c.key}\`: ${c.question}`)] : ["No Don't-build reasons to confirm."])]);
    else if (body.result === "signed_off") show(`${step.id}: sign-off`, [cmd, "", ...body.gates.flatMap((g) => [`- **${g.title}** (\`${g.item}\`): **${g.decision}**`, ...g.reasons.map((r) => `  - ${r}`), ...(g.revisit_trigger ? [`  - ${g.revisit_trigger}`] : [])])]);
    else show(`${step.id}: ${body.result}`, [cmd, "", `Files: ${(body.written ?? body.files ?? []).map?.((f) => `\`${typeof f === "string" ? f : f.file}\``).join(", ") ?? ""}`]);
  }
  return md.join("\n");
}

if (import.meta.url === `file://${process.argv[1].replace(/\\/g, "/").replace(/^\/?/, "/")}` || process.argv[1]?.endsWith("replay-async-example.mjs")) {
  const { results, packet, final, early } = replay();
  for (const { step, body } of results) console.log(`${step.id}: ${body.result}`);
  if (process.argv.includes("--write")) {
    const out = join(EXAMPLE, "output");
    rmSync(out, { recursive: true, force: true });
    for (const [name, files] of [["final", final], ["early", early]]) {
      mkdirSync(join(out, name), { recursive: true });
      for (const [f, text] of Object.entries(files)) writeFileSync(join(out, name, f), text);
    }
    writeFileSync(join(EXAMPLE, "walkthrough.md"), walkthrough(results) + "\n");
    writeFileSync(join(EXAMPLE, "packet.md"), packet);
    console.log(`wrote ${EXAMPLE}/walkthrough.md and ${out}/{final,early}`);
  }
}
